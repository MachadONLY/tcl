import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import process from "node:process";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENV_PATH = path.join(ROOT, ".env.local");
const OUTPUT_PATH = path.join(ROOT, "src", "data", "premier-league-player-faces.js");
const API_BASE = "https://v3.football.api-sports.io";
const LEAGUE_ID = 39;

function parseEnv(text) {
  return Object.fromEntries(
    text
      .split(/\r?\n/)
      .map(line => line.trim())
      .filter(line => line && !line.startsWith("#") && line.includes("="))
      .map(line => {
        const index = line.indexOf("=");
        const key = line.slice(0, index).trim();
        const value = line.slice(index + 1).trim().replace(/^['"]|['"]$/g, "");
        return [key, value];
      })
  );
}

async function localEnv() {
  try {
    return parseEnv(await readFile(ENV_PATH, "utf8"));
  } catch {
    return {};
  }
}

function normalizeName(value) {
  return String(value || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[.'’`-]/g, " ")
    .replace(/\b(jr|junior|sr|ii|iii|iv)\b/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function wait(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

async function request(endpoint, apiKey) {
  const response = await fetch(`${API_BASE}${endpoint}`, {
    headers: {
      "x-apisports-key": apiKey
    }
  });

  if (!response.ok) {
    throw new Error(`API-Football returned HTTP ${response.status} for ${endpoint}`);
  }

  const payload = await response.json();
  const errors = payload?.errors;
  if (errors && ((Array.isArray(errors) && errors.length) || (!Array.isArray(errors) && Object.keys(errors).length))) {
    throw new Error(`API-Football error for ${endpoint}: ${JSON.stringify(errors)}`);
  }

  return payload?.response || [];
}

function serializeModule(meta, players) {
  return `// Generated by scripts/sync-premier-league-faces.mjs. Do not edit manually.\n\n` +
    `export const PLAYER_FACE_META = Object.freeze(${JSON.stringify(meta, null, 2)});\n\n` +
    `export const PREMIER_LEAGUE_PLAYERS = Object.freeze(${JSON.stringify(players, null, 2)});\n\n` +
    `export default PREMIER_LEAGUE_PLAYERS;\n`;
}

async function main() {
  const env = { ...(await localEnv()), ...process.env };
  const apiKey = env.API_FOOTBALL_KEY;
  const season = Number(env.PREMIER_LEAGUE_SEASON || 2026);

  if (!apiKey) {
    throw new Error(
      "Missing API_FOOTBALL_KEY. Add it to .env.local or your shell environment before running this script."
    );
  }

  console.log(`Syncing Premier League ${season}/${String(season + 1).slice(-2)} player faces...`);

  const teamResponse = await request(`/teams?league=${LEAGUE_ID}&season=${season}`, apiKey);
  const teams = teamResponse
    .map(item => item?.team)
    .filter(Boolean)
    .sort((a, b) => a.name.localeCompare(b.name));

  if (!teams.length) {
    throw new Error(`No Premier League teams were returned for season ${season}.`);
  }

  const playerMap = new Map();

  for (const [index, team] of teams.entries()) {
    console.log(`[${index + 1}/${teams.length}] ${team.name}`);
    const squadResponse = await request(`/players/squads?team=${team.id}`, apiKey);
    const squad = squadResponse[0]?.players || [];

    for (const player of squad) {
      if (!player?.id || !player?.name) continue;

      const record = {
        id: player.id,
        name: player.name,
        normalizedName: normalizeName(player.name),
        age: player.age ?? null,
        number: player.number ?? null,
        position: player.position ?? null,
        photo: player.photo || `https://media.api-sports.io/football/players/${player.id}.png`,
        teamId: team.id,
        teamName: team.name,
        teamCode: team.code || null,
        teamLogo: team.logo || `https://media.api-sports.io/football/teams/${team.id}.png`
      };

      const existing = playerMap.get(player.id);
      if (!existing || existing.teamName !== team.name) playerMap.set(player.id, record);
    }

    // Gentle pacing avoids request bursts while still finishing a 20-team sync quickly.
    await wait(220);
  }

  const players = [...playerMap.values()].sort((a, b) => {
    const teamComparison = a.teamName.localeCompare(b.teamName);
    return teamComparison || a.name.localeCompare(b.name);
  });

  const meta = {
    source: "api-football",
    leagueId: LEAGUE_ID,
    leagueName: "Premier League",
    season,
    generatedAt: new Date().toISOString(),
    teamCount: teams.length,
    playerCount: players.length
  };

  await mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await writeFile(OUTPUT_PATH, serializeModule(meta, players), "utf8");

  console.log(`Done: ${players.length} players across ${teams.length} clubs.`);
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_PATH)}`);
}

main().catch(error => {
  console.error(`\nPlayer face sync failed: ${error.message}`);
  process.exitCode = 1;
});
